def convert(m):
    safety, setup, easier, harder = EXTRA[m["id"]]
    return {
        "id": m["id"],
        "name": m["title"],
        "tagline": m["summary"],
        "categories": m["categories"],
        "age_min": m["ages"][0],
        "age_max": m["ages"][1],
        "group_min": m["group"][0],
        "group_max": m["group"][1],
        "time_min": m["time_min"],
        "time_max": m["time_min"],
        "location": m["setting"],
        "materials": [{"item": x} for x in m["materials"]],
        "no_prep": len(m["materials"]) == 0,
        "safety": safety,
        "setup": setup,
        "steps": m["instructions"],
        "variations": {"easier": easier, "harder": harder},
    }

def main():
    mine = []
    for i in range(1, 7):
        mine.extend(json.load(open(f"{DATA}/chunk{i}.json")))
    theirs = json.load(open(f"{DATA}/activities.json"))
    have = {a["id"] for a in theirs}
    added = 0
    for m in mine:
        if m["id"] in SKIP_IDS or m["id"] in have:
            continue
        assert m["id"] in EXTRA, m["id"]
        theirs.append(convert(m))
        added += 1
    # add music-rhythm category
    cats = json.load(open(f"{DATA}/categories.json"))
    if not any(c["id"] == "music-rhythm" for c in cats):
        cats.append({"id": "music-rhythm", "name": "Music & Rhythm", "glyph": "🥁",
                     "color": "#a855f7",
                     "blurb": "Drums, shakers, rhythm games, and songs — make some noise."})
        json.dump(cats, open(f"{DATA}/categories.json", "w"), indent=2)
    json.dump(theirs, open(f"{DATA}/activities.json", "w"), indent=2, ensure_ascii=False)
    print(f"added {added}; total {len(theirs)}")

if __name__ == "__main__":
    main()
