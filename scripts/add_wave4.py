# Tags for existing fall/halloween activities (already in the library)
EXISTING_TAGS = {
    "no-carve-pumpkin-decorating": ["season:fall", "holiday:halloween"],
    "fall-sensory-jars": ["season:fall"],
    "pumpkin-painting-party": ["season:fall", "holiday:halloween"],
    "halloween-shadow-puppets": ["holiday:halloween", "theme:spooky"],
    "halloween-pumpkin-bowl": ["season:fall", "holiday:halloween"],
}

def main():
    acts = json.load(open(os.path.join(DATA, 'activities.json')))
    ids = {a['id'] for a in acts}
    new = FALL_PACK + RSS_PROMOTED
    dupes = [a['id'] for a in new if a['id'] in ids]
    if dupes:
        print("DUPLICATE IDS:", dupes)
        sys.exit(1)
    # id-collision check within the new batch itself
    seen = set()
    for a in new:
        if a['id'] in seen:
            print("INTERNAL DUPE:", a['id']); sys.exit(1)
        seen.add(a['id'])
    tagged = 0
    for a in acts:
        if a['id'] in EXISTING_TAGS and not a.get('tags'):
            a['tags'] = EXISTING_TAGS[a['id']]
            tagged += 1
    acts.extend(new)
    json.dump(acts, open(os.path.join(DATA, 'activities.json'), 'w'),
              indent=1, ensure_ascii=False)
    print(f"OK — added {len(new)} activities ({len(FALL_PACK)} fall pack + "
          f"{len(RSS_PROMOTED)} RSS), tagged {tagged} existing. Total: {len(acts)}.")

if __name__ == '__main__':
    main()
