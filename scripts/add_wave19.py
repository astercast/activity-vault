def main():
    acts = json.load(open(DATA))
    existing = {a['id'] for a in acts}
    new_ids = [a['id'] for a in ACTS]
    assert len(new_ids) == len(set(new_ids)), "dupes inside the wave pack"
    assert len(ACTS) == 60, f"expected 60, got {len(ACTS)}"
    for a in ACTS:
        if a['id'] in existing:
            print(f"COLLISION: {a['id']}", file=sys.stderr); sys.exit(1)
        if not ID_RE.match(a['id']):
            print(f"BAD ID: {a['id']}", file=sys.stderr); sys.exit(1)
        for f in ('id','name','tagline','categories','age_min','age_max','group_min',
                  'group_max','time_min','time_max','location','materials','no_prep',
                  'setup','steps','variations'):
            if f not in a:
                print(f"{a['id']}: missing {f}", file=sys.stderr); sys.exit(1)
        if a['time_max'] > 10 or a['time_min'] < 5:
            print(f"{a['id']}: not a 5-10 micro activity", file=sys.stderr); sys.exit(1)
        if not a['no_prep']:
            print(f"{a['id']}: not no_prep", file=sys.stderr); sys.exit(1)
        if len(a['tagline']) > 160:
            print(f"{a['id']}: tagline too long", file=sys.stderr); sys.exit(1)
        if len(a['steps']) < 3:
            print(f"{a['id']}: too few steps", file=sys.stderr); sys.exit(1)
        v = a['variations']
        if 'easier' not in v or 'harder' not in v:
            print(f"{a['id']}: bad variations", file=sys.stderr); sys.exit(1)
    acts.extend(ACTS)
    json.dump(acts, open(DATA, 'w'), indent=2, ensure_ascii=False)
    open(DATA, 'a').write('\n')
    print(f"added {len(ACTS)} -> {len(acts)} activities total")

if __name__ == '__main__':
    main()
